//! What a Wikidata answer means: which items in it are referents at all.
//!
//! Pure JSON in, candidates out. Nothing here fetches, and nothing here knows the request that
//! produced the answer. The stored annotation a decided candidate becomes is `candidate`'s
//! conversion, not this module's.
//!
//! This is the only filter the ranking keeps. Everything else about a candidate — which name it
//! bears, which kind it is, which strategy produced it — is the ranking's question, answered by
//! scoring in [`super::ranking`]. The ladder's per-strategy admission, its early exits and its
//! type gate were removed with the ladder: they decided *before* the ranking, which is how `BBC`
//! had `Q9531` at the top of two answers and still claimed a division — the right item was
//! excluded, not outranked.

use super::WikidataCandidate;
use crate::fetch::Answer;

/// A menu, not a referent. Two classes because Wikidata's own hierarchy defeats equality: `Q22808320`
/// ("Wikimedia human name disambiguation page") is a *subclass* of `Q4167410`, and every one of the 34
/// disambiguation pages the corpus had claimed carried the subclass, none the parent.
const MENUS: [&str; 2] = [
    "Q4167410",  // Wikimedia disambiguation page
    "Q22808320", // Wikimedia human name disambiguation page
];

/// A disambiguation page, or an item that is otherwise a list rather than a thing.
///
/// Two signals because neither is complete: the class list is structural but misses items stored
/// with no classes at all (three of the corpus's), while the autogenerated description is a
/// convention that caught all 34.
pub(super) fn is_menu(candidate: &WikidataCandidate) -> bool {
    candidate
        .classes
        .iter()
        .any(|class| MENUS.contains(&class.as_str()))
        || candidate
            .description
            .as_deref()
            .is_some_and(|text| text.to_lowercase().contains("disambiguation"))
}

/// The candidates that are referents at all: an answered question with something left after the
/// menus are dropped.
pub(crate) fn referents(
    raw: &Answer<Vec<WikidataCandidate>>,
) -> Result<Vec<WikidataCandidate>, &'static str> {
    if !raw.outcome.answered() {
        return Err("the answer carried no candidate");
    }
    let mut candidates = raw.body.clone().unwrap_or_default();
    candidates.retain(|candidate| !is_menu(candidate));
    if candidates.is_empty() {
        return Err("the answer carried only a disambiguation page");
    }
    Ok(candidates)
}
