// Bump for model or manual-index changes that require an explicit schema sync.
const REQUIRED_SCHEMA_VERSION: i32 = 33;

/// Schema 23 reshapes claims into an edge — entity plus identity — and keys collisions by identity.
///
/// Both tables regenerate from `link` + `resolve`, and the old shape cannot be migrated in place: the
/// new `knowledge_identity_id` is `NOT NULL` and the old rows have nothing to put in it. Guarded on
/// the old column, so a synced database is left alone. Runs before the registry, which would
/// otherwise try to alter a populated table.
///
/// Also drops the single-holder index, which the registry would otherwise try to alter as a
/// constraint of that name.
/// Schema 28 folds the old per-generation merge audit into `knowledge_verdicts`, which is now the
/// one modification log. The old table's rows are keys into entity ids that a rebuild renumbers, so
/// there is nothing worth migrating; they were snapshotted by reset anyway.
/// Schema 29 gives `knowledge_verdicts` a second kind: a `veto` names one entity and one identity, so
/// the merge columns have nothing to hold. They are relaxed here rather than declared nullable in the
/// registry, which would try to rewrite a populated table. Guarded, so a synced database is untouched.
async fn relax_verdict_columns<C: ConnectionTrait>(conn: &C) -> Result<(), DbErr> {
    conn.execute_unprepared(
        "DO $$ BEGIN \
           IF EXISTS (SELECT 1 FROM information_schema.columns \
                       WHERE table_schema = current_schema() \
                         AND table_name = 'knowledge_verdicts' \
                         AND column_name = 'winner_origin' \
                         AND is_nullable = 'NO') THEN \
             ALTER TABLE knowledge_verdicts ALTER COLUMN winner_origin DROP NOT NULL; \
             ALTER TABLE knowledge_verdicts ALTER COLUMN loser_origin DROP NOT NULL; \
           END IF; \
         END $$",
    )
    .await?;
    Ok(())
}

/// Schema 30 renames `knowledge_identities.source` to `asserted_by`.
///
/// The column holds four kinds of asserter — a capture (`platform`), an authority, and eventually a
/// model — so `source` named only one of them. The registry can only *add* a column, and
/// `asserted_by` is `NOT NULL` with no default, which a populated table cannot take: the rename has
/// to happen before it. Guarded, so a synced database is untouched.
async fn rename_identity_asserted_by<C: ConnectionTrait>(conn: &C) -> Result<(), DbErr> {
    conn.execute_unprepared(
        "DO $$ BEGIN \
           IF EXISTS (SELECT 1 FROM information_schema.columns \
                       WHERE table_schema = current_schema() \
                         AND table_name = 'knowledge_identities' \
                         AND column_name = 'source') THEN \
             ALTER TABLE knowledge_identities RENAME COLUMN source TO asserted_by; \
           END IF; \
         END $$",
    )
    .await?;
    Ok(())
}

async fn retire_merge_audit<C: ConnectionTrait>(conn: &C) -> Result<(), DbErr> {
    conn.execute_unprepared("DROP TABLE IF EXISTS knowledge_merges")
        .await?;
    Ok(())
}

/// Schema 26 makes proximities one scan's output rather than a ledger: `verdict` and `settled_at`
